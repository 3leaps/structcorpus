#!/usr/bin/env python3
"""Prepare a public tag message outside the repository, without clobber.

A new message is drafted from the release's dated CHANGELOG.md section, copied
as written once the changelog passes the release-surface guard. It carries a
review marker that the validator refuses, so the draft cannot be tagged until
someone has edited it.
"""

import os
import re
import subprocess
import sys
from pathlib import Path
from typing import Optional

FOOTER = re.compile(
    r"(?:^|\n\n)"
    r"Role: [a-z][a-z0-9-]*\n"
    r"Co-[Aa]uthored-[Bb]y: .+ <noreply@3leaps\.net>\n"
    r"Committer-of-Record: @3leapsdave\n$"
)
RETIRED_FOOTER = re.compile(r"(?:^|\n)Generated by .+ via .+ under supervision of @")
PLACEHOLDER = re.compile(
    r"<(?:[A-Z][A-Z -]*|model|interface[^<>]*|role|TODO[^<>]*|REPLACE[^<>]*)>",
    re.I,
)
REVIEW_MARKER = "<REVIEW AND EDIT THE DRAFT BELOW THEN DELETE THIS LINE>"
# Lines Markdown could read as a level-one or level-two heading (ATX, or a
# setext underline) or that a reader could take as a section break. Inside a
# release section only "###" and deeper headings are accepted.
SECTION_BOUNDARY = re.compile(r"^ {0,3}(?:#{1,2}(?:[ \t]|$)|=+[ \t]*$|-+[ \t]*$)")


def fail(reason: str) -> None:
    raise ValueError(reason)


def subject_for(tag: str) -> str:
    return f"Release {tag[1:]}" if tag.startswith("v") else tag


def validate_message(data: bytes, subject: Optional[str] = None) -> str:
    try:
        message = data.decode("utf-8")
    except UnicodeError:
        fail("tag message must be UTF-8")
    if (
        not data
        or b"\x00" in data
        or b"\r" in data
        or not data.endswith(b"\n")
        or data.endswith(b"\n\n")
        or any(line.rstrip(b" \t") != line for line in data.splitlines())
    ):
        fail("tag message needs one final newline and no CR, NUL or trailing whitespace")
    if PLACEHOLDER.search(message):
        fail("tag message contains an unresolved placeholder")
    if RETIRED_FOOTER.search(message) or not FOOTER.search(message):
        fail("tag message must end with the complete attribution footer")
    if subject is not None and message.split("\n", 1)[0] != subject:
        fail(f"tag message subject must be {subject!r}")
    return message


def changelog_section(text: str, version: str) -> list:
    """Return the release section's body lines exactly as written.

    The changelog has already passed release-guard-release-surfaces.sh, so it
    is printable ASCII with no fenced code, the release label appears only in
    its dated heading, and "]:" appears only in the final link-definition
    footer. A column-zero "## " line therefore starts the next section, and a
    line containing "]:" starts the footer. Any other line that could start a
    section is refused rather than interpreted.
    """
    heading = f"## [{version}] - "
    lines = text.split("\n")
    starts = [
        index
        for index, line in enumerate(lines)
        if line.startswith(heading) and re.fullmatch(r"\d{4}-\d{2}-\d{2}", line[len(heading) :])
    ]
    if len(starts) != 1:
        fail(f"CHANGELOG.md needs exactly one dated section for {version}")
    body = []
    for line in lines[starts[0] + 1 :]:
        if line.startswith("## ") or "]:" in line:
            break
        body.append(line)
    for line in body:
        if SECTION_BOUNDARY.match(line):
            fail(
                f"CHANGELOG.md section for {version} has a line that could start another section; "
                "use '## [x.y.z] - YYYY-MM-DD' headings and '###' or deeper inside a section"
            )
    while body and not body[0].strip():
        body.pop(0)
    while body and not body[-1].strip():
        body.pop()
    if not body:
        fail(f"CHANGELOG.md section for {version} is empty")
    return body


def draft(root: Path, tag: str) -> bytes:
    """Draft a message from the changelog section, copied without reformatting."""
    guard = root / "scripts" / "release-guard-release-surfaces.sh"
    if subprocess.run([str(guard)], cwd=root, stdin=subprocess.DEVNULL).returncode != 0:
        fail("CHANGELOG.md must pass the release-surface guard before a message is drafted")
    try:
        changelog = (root / "CHANGELOG.md").read_bytes().decode("ascii")
    except (OSError, UnicodeError):
        fail("CHANGELOG.md must be a readable printable-ASCII file")
    summary = "\n".join(changelog_section(changelog, tag[1:]))
    return (
        f"{subject_for(tag)}\n\n"
        f"{REVIEW_MARKER}\n\n"
        f"{summary}\n\n"
        "Role: <role>\n"
        "Co-authored-by: <model> <noreply@3leaps.net>\n"
        "Committer-of-Record: @3leapsdave\n"
    ).encode("utf-8")


def message_dir(root: Path, tag: str) -> Path:
    raw = os.environ.get("STRUCTCORPUS_TAG_MESSAGE_DIR", "")
    directory = Path(raw)
    if not raw or not directory.is_absolute() or ".." in directory.parts or directory.name != tag:
        fail("external absolute per-cut message directory ending in release tag required")

    current = Path(directory.anchor)
    for part in directory.parts[1:]:
        current /= part
        if current.is_symlink():
            fail("message directory may not contain symlink ancestors")
    resolved = directory.resolve(strict=False)
    for candidate in (directory, resolved):
        for ancestor in (candidate, *candidate.parents):
            try:
                if ancestor.exists() and os.path.samefile(ancestor, root):
                    fail("message directory must be outside the repository")
            except OSError:
                continue
    if resolved == root or root in resolved.parents:
        fail("message directory must be outside the repository")
    if resolved.name != tag:
        fail("message directory must resolve to a directory named for the release tag")
    directory.mkdir(mode=0o700, parents=True, exist_ok=True)
    if directory.is_symlink() or not directory.is_dir():
        fail("message directory must be a real directory")
    return directory


def prepare() -> None:
    root = Path(__file__).resolve().parent.parent
    if "RELEASE_TAG" in os.environ:
        fail("generic RELEASE_TAG alias is forbidden; unset it and use STRUCTCORPUS_RELEASE_TAG")
    tag = os.environ.get("STRUCTCORPUS_RELEASE_TAG", "")
    if tag != f"v{(root / 'VERSION').read_text().strip()}":
        fail("release tag must match VERSION")
    skeleton = draft(root, tag)
    directory = message_dir(root, tag)

    file = directory / f"{tag.replace('/', '__')}.txt"
    try:
        descriptor = os.open(file, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    except FileExistsError:
        state = "preserved"
    else:
        try:
            with os.fdopen(descriptor, "wb") as output:
                output.write(skeleton)
        except OSError:
            file.unlink(missing_ok=True)
            raise
        state = "created"
    if file.is_symlink() or not file.is_file():
        fail(f"{file.name} must be a regular non-symlink file")
    try:
        message = validate_message(file.read_bytes(), subject_for(tag))
        status = "complete"
    except ValueError as error:
        message = file.read_text(encoding="utf-8", errors="replace")
        status = f"incomplete: {error}"
    print(f"[{'ok' if status == 'complete' else '..'}] {state} {file.name} ({status}):")
    print(message, end="")


def main() -> None:
    args = sys.argv[1:]
    if len(args) in (2, 3) and args[0] == "--validate-message":
        subject = args[2] if len(args) == 3 else None
        validate_message(Path(args[1]).read_bytes(), subject)
    elif not args:
        prepare()
    else:
        fail("expected prepare or validate-message mode")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError) as error:
        # Never echo a loader path or raw message-directory path.
        detail = str(error) if isinstance(error, ValueError) else "unable to prepare external tag message"
        print(f"error: {detail}", file=sys.stderr)
        sys.exit(1)
